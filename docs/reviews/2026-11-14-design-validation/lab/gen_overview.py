def mask_sql(text):
    """The SQL text with comments and string literals replaced by spaces (newlines kept), so positions stay valid."""
    out, i, n = list(text), 0, len(text)
    while i < n:
        if text.startswith("--", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out[i:j] = " " * (j - i)
            i = j
        elif text[i] == "'":
            j = i + 1
            while j < n and not (text[j] == "'" and not text.startswith("''", j)):
                j += 2 if text.startswith("''", j) else 1
            out[i + 1:j] = [c if c == "\n" else " " for c in text[i + 1:j]]
            i = j + 1
        elif text[i] == "$" and re.match(r"\$[A-Za-z_]*\$", text[i:]):
            tag = re.match(r"\$[A-Za-z_]*\$", text[i:]).group(0)
            j = text.find(tag, i + len(tag))
            j = n if j < 0 else j
            out[i + len(tag):j] = [c if c == "\n" else " " for c in text[i + len(tag):j]]
            i = j + len(tag)
        else:
            i += 1
    return "".join(out)


def table_spans(text, masked):
    """[(table, open paren index, close paren index, [(start, end) of each top-level element])] of every CREATE TABLE
    with a column list (partitions, CREATE TABLE ... PARTITION OF, inherit from their parent and are skipped)."""
    out = []
    for m in re.finditer(r"^CREATE TABLE (\w+) \(", masked, re.M):
        start = i = m.end() - 1
        depth, elems, cur = 0, [], None
        while True:
            ch = masked[i]
            if ch == "(":
                depth += 1
                if depth == 1:
                    cur = i + 1
            elif ch == ")":
                depth -= 1
                if depth == 0:
                    elems.append((cur, i))
                    break
            elif ch == "," and depth == 1:
                elems.append((cur, i))
                cur = i + 1
            i += 1
        spans = []
        for s, e in elems:
            seg = masked[s:e]
            spans.append((s + len(seg) - len(seg.lstrip()), s + len(seg.rstrip())))
        out.append((m.group(1), start, i, spans))
    return out


# Append-only classification (schema_phase_b.py imports it): a table whose BEFORE UPDATE guard refuses every update outside
# an erasure (ALWAYS_REFUSE, or an ARG_GUARDS function with no mutable column but recorded_at and no set-once column), and
# the pure logs.
ALWAYS_REFUSE = {"platform_reject_change", "inventory_reject_change", "journal_reject_change", "audit_refuse_change",
                 "document_reader_reject_change", "document_version_check_change", "product_configuration_immutable"}
ARG_GUARDS = {"platform_check_append_only", "crm_check_append_only"}
CLASSIFY_RE = re.compile(r"\s*CREATE (?:OR REPLACE )?TRIGGER (\w+)\s+BEFORE\s+(.*?)\s+ON (?:\w+\.)?(\w+).*?"
                         r"EXECUTE FUNCTION (?:\w+\.)?(\w+)\((.*?)\)\s*;?\s*$", re.S)


def classify(stmts):
    """Append-only tables of all files (table -> reason), from comment-free statements."""
    out = {t: "pure log" for t in PURE_LOGS}
    for code in stmts:
        m = CLASSIFY_RE.match(code)
        if not m or not re.search(r"\bUPDATE\b", m.group(2)):
            continue
        table, fn, args = m.group(3), m.group(4), m.group(5)
        if fn in ALWAYS_REFUSE:
            out[table] = fn
        elif fn in ARG_GUARDS:
            arrays = re.findall(r"'\{([^}]*)\}'", args)
            mutable = {c.strip() for c in arrays[0].split(",") if c.strip()}
            set_once = {c.strip() for c in arrays[1].split(",") if c.strip()}
            if mutable <= {"recorded_at"} and not set_once:
                out[table] = fn
    return out


# Company keys (ADR-0017 rule 19 note of 2026-11-21; open question R2-N9): a foreign key from a company table (company_id
# NOT NULL) to a company table is composite, FOREIGN KEY (company_id, x) REFERENCES t (company_id, id). A single-column key
# where either side has a nullable company_id (installation-or-company rows) stays single-column; that table must be listed
# here with its reason, and an entry whose table no longer has a nullable company_id, or no such key, fails.
COMPANY_KEY_ALLOWLIST = {
    "uom": "target: core units have company_id null (ADR-0018 rule 8); a composite key would refuse them",
    "audit_record": "target: installation-scoped audit rows have company_id null (ADR-0017 rule 19)",
    "audit_change": "referencing table: installation-scoped audit rows have company_id null (ADR-0017 rule 19)",
    "outbox_event": "target: installation-scoped events have company_id null (ADR-0013 rule 14)",
    "event_delivery": "referencing table: installation-scoped deliveries have company_id null (ADR-0013 rule 14)",
}
FK_ELEMENT_RE = re.compile(r"(?:CONSTRAINT \w+ )?FOREIGN KEY \(([^)]*)\) REFERENCES (\w+) \(([^)]*)\)")
FK_COLUMN_RE = re.compile(r"\bREFERENCES (\w+) \(([^)]*)\)")
FK_ALTER_RE = re.compile(r"^ALTER TABLE (\w+)\s+ADD\s+(?:CONSTRAINT \w+\s+)?FOREIGN KEY\s*\(([^)]*)\)\s*REFERENCES (\w+)\s*\(([^)]*)\)", re.M)
UQ_COMPANY_RE = re.compile(r"(?:CONSTRAINT \w+ )?UNIQUE \(company_id, id\)")
UQ_ALTER_RE = re.compile(r"^ALTER TABLE (\w+)\s+ADD\s+(?:CONSTRAINT \w+\s+)?UNIQUE \(company_id, id\)", re.M)


def company_scan(named_texts):
    """From [(file name, SQL text)]: tables {name: {"company": None | "null" | "not null", "uq": bool, "file": str,
    "where": str}} and foreign keys [(where, file, table, [columns], target, [target columns])], read from CREATE TABLE
    elements (column REFERENCES and table FOREIGN KEY) and ALTER TABLE ... ADD FOREIGN KEY."""
    split = lambda s: [x.strip() for x in s.split(",")]
    tables, fks = {}, []
    for fname, text in named_texts:
        masked = mask_sql(text)
        line = lambda pos: f"{fname}:{text.count(chr(10), 0, pos) + 1}"
        for name, _, _, spans in table_spans(text, masked):
            info = {"company": None, "uq": False, "file": fname, "where": line(spans[0][0])}
            for s, e in spans:
                c = " ".join(masked[s:e].split())
                if UQ_COMPANY_RE.fullmatch(c):
                    info["uq"] = True
                fm = FK_ELEMENT_RE.match(c)
                if fm:
                    fks.append((line(s), fname, name, split(fm.group(1)), fm.group(2), split(fm.group(3))))
                elif not re.match(r"(CONSTRAINT|UNIQUE|CHECK|EXCLUDE|PRIMARY|FOREIGN)\b", c):
                    col = c.split()[0]
                    if col == "company_id":
                        info["company"] = "not null" if "NOT NULL" in c else "null"
                    rm = FK_COLUMN_RE.search(c)
                    if rm:
                        fks.append((line(s), fname, name, [col], rm.group(1), split(rm.group(2))))
            tables[name] = info
        for m in UQ_ALTER_RE.finditer(masked):
            if m.group(1) in tables:
                tables[m.group(1)]["uq"] = True
        for m in FK_ALTER_RE.finditer(masked):
            fks.append((line(m.start()), fname, m.group(1), split(m.group(2)), m.group(3), split(m.group(4))))
    return tables, fks


def check_company_keys(docs):
    """Errors for the company-key rule (COMPANY_KEY_ALLOWLIST's comment) over design/*.sql, and its counts. Where
    00_stubs.sql is present, a stub table that a composite company key of another design file targets must have
    company_id NOT NULL and UNIQUE (company_id, id), since a lab may load that file with the stub."""
    design = os.path.join(docs, "design")
    texts = [(f"design/{f}", read(os.path.join(design, f))) for f in sorted(os.listdir(design)) if f.endswith(".sql")]
    tables, fks = company_scan(texts)
    errors, single, composite, used = [], 0, 0, set()
    company = lambda t: tables.get(t, {}).get("company")
    for where, _, src, cols, tgt, tcols in fks:
        if company(src) is None or company(tgt) is None:
            continue                                  # installation tables (no company_id) stay single-column
        if "company_id" in cols:
            composite += 1
            if tcols[cols.index("company_id")] != "company_id":
                errors.append(f"{where}: foreign key {src} ({', '.join(cols)}) -> {tgt} pairs company_id with "
                              f"{tcols[cols.index('company_id')]}")
            continue
        if len(cols) != 1:
            continue                                  # multi-column keys without company_id: outside the rule (the note)
        if company(src) == "not null" and company(tgt) == "not null":
            errors.append(f"{where}: single-column foreign key between company tables, {src}.{cols[0]} -> {tgt}; write "
                          f"FOREIGN KEY (company_id, {cols[0]}) REFERENCES {tgt} (company_id, id) (ADR-0017 rule 19 note; "
                          "schema_phase_b.py rule 3)")
            continue
        single += 1
        nullable = [t for t in (src, tgt) if company(t) == "null"]
        missing = [t for t in nullable if t not in COMPANY_KEY_ALLOWLIST]
        used.update(t for t in nullable if t in COMPANY_KEY_ALLOWLIST)
        if missing:
            errors.append(f"{where}: single-column foreign key {src}.{cols[0]} -> {tgt}, where {', '.join(missing)} has a "
                          "nullable company_id and is not in COMPANY_KEY_ALLOWLIST")
    for t in sorted(set(COMPANY_KEY_ALLOWLIST) - used):
        errors.append(f"COMPANY_KEY_ALLOWLIST names {t}, which has no nullable company_id or no single-column key; remove it")
    stub_path = os.path.join(docs, STUBS)
    if os.path.exists(stub_path):
        stubs, _ = company_scan([(STUBS, read(stub_path))])
        targets = {tgt for _, f, src, cols, tgt, _ in fks
                   if "company_id" in cols and company(src) == "not null" and tables.get(tgt, {}).get("file") != f}
        for t in sorted(targets & set(stubs)):
            if not stubs[t]["uq"] or stubs[t]["company"] != "not null":
                errors.append(f"{stubs[t]['where']}: lab stub {t} is the target of composite company keys but lacks "
                              "company_id NOT NULL or UNIQUE (company_id, id)")
    return errors, {"company_keys": composite, "company_key_exceptions": single}


def design_statements(design):
    """Comment-free statements of every design/*.sql file."""
    sys.path.insert(0, HERE)
    from load_all import split_statements
    stmts = []
    for f in sorted(os.listdir(design)):
        if f.endswith(".sql"):
            stmts += [re.sub(r"--[^\n]*", "", st) for st, _ in split_statements(read(os.path.join(design, f)), f)[0]]
