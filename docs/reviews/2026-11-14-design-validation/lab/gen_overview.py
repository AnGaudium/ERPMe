def adr_links_from_generated(text):
    """Rewrite relative links copied from an ADR so they resolve from design/generated/."""
    def fix(m):
        target = m.group(1)
        if re.match(r"[a-z]+:", target):
            return m.group(0)
        path, _, anchor = target.partition("#")
        new = os.path.relpath(os.path.normpath(os.path.join("adr", path)), os.path.join("design", "generated"))
        return "](" + new.replace(os.sep, "/") + ("#" + anchor if anchor else "") + ")"
    return re.sub(r"\]\(([^)\s]+)\)", fix, text)


