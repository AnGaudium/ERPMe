CREATE_RE = re.compile(r"^CREATE TABLE (\w+)\s*\(")
SECTION_RE = re.compile(r"^--\s*=====\s*(.*?)\s*=====\s*$")
BRACKET_RE = re.compile(r"\[([^\]]+)\]")
