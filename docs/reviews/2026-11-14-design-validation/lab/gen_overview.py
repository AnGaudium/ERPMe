def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def rel(docs, path):
    return "docs/" + os.path.relpath(path, docs).replace(os.sep, "/")


def snake(pascal):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", pascal).lower()


def camel_words(pascal):
    return re.findall(r"[A-Z][a-z0-9]*", pascal)


