"""Lab: generate the architecture overview appendices (Part C) from the design sources. Not product code.

`nativeflows-dev generate` (ADR-0022 rules 14, 17) does not exist yet, because there is no code. Until it does, this script
writes the generated appendices of docs/design/architecture-overview.md. `nativeflows-dev generate` takes this over at build
step 0, reading the registry and the `tables.py` MetaData instead of the DDL drafts. Like the rest of the lab, this file
is design evidence: the product never imports it (lab README).

Inputs (all under docs/):
- design/*.sql: tables, columns, foreign keys and the owner module stated in SQL comments. Ownership is read, in this
  order: a `[module]` or "owned by <module>" in the CREATE TABLE line's own comment; a sentence "<table> is owned by
  <module>" or "<table> stays a stub owned by <module>" anywhere in the file's comments; an "owned by <module>" in the
  comment block directly above the CREATE TABLE (that table only); the section header's brackets (`[module]`, or
  "<module> owns <tables>"); the file header ("Owner module: <module>", "<module> owns every table"). A section that
  names two owners assigns none. Nothing else is inferred: a table with no stated owner stays unowned.
- reviews/2026-11-14-design-validation/lab/00_stubs.sql: lab stub tables. A stub that no design file defines is a
  finding.
- adr/0022-repository-and-engineering-conventions.md: the module map (rule 2 table and its "`module` (layer n" notes).
- adr/*.md: titles, status lines, design items; event and command names in backticks; consumer names.
- spec/00-reading-guide.md: the command verb list with event forms.
- catalogs/settings.csv, work-item-kinds.csv, authorization-areas.csv.

Outputs: design/generated/{module-cards,data-map,event-matrix,adr-index}.md, sorted and stable. Purpose in the data
map is a table's own comment, never a line of another table's comment, and stays empty when none belongs to it.
ADRs per module are "declared" (ADR-0022 rule 2 notes; ADR citations in the DDL of the module's owned tables) and,
separately, "mentions" (a count of backticked names), labelled as such.

Unowned and stub tables: the script fails (exit 2) on a table with no owner, or a stub table, unless it is listed in
ACKNOWLEDGED below with the finding it belongs to. Acknowledged tables are listed as findings in data-map.md; no owner
is invented for them. An acknowledged table that later gets an owner also fails, so the list cannot go stale.

Keys and recorded_at (findings 1 and 2; check_keys_and_recorded_at): the script also fails (exit 2) on a table without
`recorded_at timestamptz NOT NULL DEFAULT now()`, on a primary key other than the single column `id uuid` unless the table
is in KEY_ALLOWLIST, and on a design file whose recorded_at trigger section (the DO block of schema_phase_b.py) does not
list exactly the file's tables, lists an append-only table without a guard trigger (outside PURE_LOGS), or leaves an
in-place table with a BEFORE UPDATE guard that sorts after its set_recorded_at trigger. Company keys (check_company_keys):
it fails on a single-column foreign key between two company tables (company_id NOT NULL on both), on a single-column key
to or from a table with a nullable company_id that COMPANY_KEY_ALLOWLIST does not list, and on a lab stub that a composite
company key targets without UNIQUE (company_id, id).

Usage:  python3 gen_overview.py [--docs DIR]          write the files
        python3 gen_overview.py --check [--docs DIR]  exit 1 if a generated file differs from what is committed
"""
