def module_map(docs):
    """Module -> (layer, note) from ADR-0022 rule 2: the layer table and its '`module` (layer n' notes."""
    text = read(os.path.join(docs, ADR0022))
    modules = {}
    for line in text.splitlines():
        m = re.match(r"^\s*\|\s*(\d)\s*·\s*([A-Za-z ]+?)\s*\|(.*)\|\s*$", line)
        if not m:
            continue
        layer, cells = int(m.group(1)), m.group(3)
        depth, flat, notes, current = 0, [], {}, None
        i = 0
        while i < len(cells):  # drop parenthesised text, keeping it as the note of the module before it
            ch = cells[i]
            if ch == "(":
                depth += 1
                start = i
                while i < len(cells) and depth:
                    i += 1
                    if i < len(cells) and cells[i] == "(":
                        depth += 1
                    elif i < len(cells) and cells[i] == ")":
                        depth -= 1
                inner = cells[start + 1:i].strip()
                if current and not any(t != current and re.fullmatch(r"[a-z_]+", t) and f"`{t}`," in cells
                                       for t in re.findall(r"`([^`]+)`", inner)):
                    notes.setdefault(current, inner)
                i += 1
                continue
            flat.append(ch)
            mm = re.match(r"`(\w+)`(:\s*([^(|]+))?", cells[i:])
            if mm:
                current = mm.group(1)
                if mm.group(3):
                    notes.setdefault(current, mm.group(3).strip().rstrip(";,"))
            i += 1
        for name in re.findall(r"`(\w+)`", "".join(flat)):
            modules.setdefault(name, (layer, notes.get(name, "")))
    for name, layer in re.findall(r"`(\w+)` \(layer (\d)", text):
        modules.setdefault(name, (int(layer), "added by a note to ADR-0022 rule 2"))
    return modules


# ----------------------------------------------------------------------------------------------- DDL

class Table:
    def __init__(self, name, path, line):
        self.name, self.path, self.line = name, path, line
        self.owner, self.owner_source, self.purpose, self.section = None, "", "", ""
        self.columns, self.candidates = [], []


def parse_owns(text, known_modules):
    """'master_data owns warehouses; inventory owns zones and bins' -> {table word: module}."""
    out = {}
    for clause in text.split(";"):
        m = re.match(r"\s*(\w+) owns (.+)", clause)
        if m and m.group(1) in known_modules:
            for word in re.split(r",\s*|\s+and\s+", m.group(2)):
                word = word.strip().rstrip(".")
                if word:
                    out[word] = m.group(1)
                    if word.endswith("s"):
                        out[word[:-1]] = m.group(1)
    return out


def parse_ddl(docs, modules):
    tables, fks, problems = {}, [], []
    design = os.path.join(docs, "design")
    for fname in sorted(f for f in os.listdir(design) if f.endswith(".sql")):
        path = os.path.join(design, fname)
        lines = read(path).splitlines()
        comments = "\n".join(l for l in lines if l.lstrip().startswith("--"))
        flat_comments = re.sub(r"\s*\n--\s*", " ", comments)
        file_default = None
        head = " ".join(l.lstrip("- ") for l in lines[:40] if l.startswith("--"))
        m = re.search(r"Owner module:\s*(\w+)", head) or re.search(r"(\w+)(?: \(layer \d\))? owns every table", head)
        if m and m.group(1) in modules:
            file_default = m.group(1)
        named = {}
        for t, mod in re.findall(r"\b(\w+) is owned by (\w+)", flat_comments):
            named[t] = mod
        for t, mod in re.findall(r"\b(\w+) stays a stub owned by (\w+)", flat_comments):
            named[t] = mod
        for t, mod in re.findall(r"\b(\w+) \[(\w+)\]\s*\(", flat_comments):  # "personal_data_processing_log [audit] ("
            if mod in modules:
                named.setdefault(t, mod)
        for group, mod in re.findall(r"\b((?:\w+, )*\w+ and \w+) are owned by (\w+)", flat_comments):
            for t in re.split(r",\s*|\s+and\s+", group):
                named[t] = mod
        sec_title, sec_owner, sec_multi, sec_owns = "", None, [], {}
        current = None
        pending_section = None
        for idx, line in enumerate(lines, start=1):
            if pending_section is not None:
                pending_section += " " + line.lstrip("- ").strip()
                if line.rstrip().endswith("====="):
                    line, pending_section = pending_section, None
                else:
                    continue
            elif re.match(r"^--\s*=====", line) and not line.rstrip().endswith("=====", 8):
                pending_section = line
                continue
            sm = SECTION_RE.match(line)
            if sm:
                sec_title = BRACKET_RE.sub("", sm.group(1)).split("(")[0].strip()
                sec_owner, sec_multi, sec_owns = None, [], {}
                bm = BRACKET_RE.search(sm.group(1))
                if bm:
                    inner = bm.group(1).strip()
                    if " owns " in inner:
                        sec_owns = parse_owns(inner, modules)
                    else:
                        names = [n.strip() for n in inner.split(",")]
                        if len(names) == 1:
                            sec_owner = names[0]
                        else:
                            sec_multi = names
                current = None
                continue
            cm = CREATE_RE.match(line)
            if cm:
                name = cm.group(1)
                if name in tables:
                    problems.append(f"{name} defined twice ({rel(docs, path)}:{idx})")
                t = Table(name, rel(docs, path), idx)
                t.section = sec_title
                trailing = line.split("--", 1)[1].strip() if "--" in line else ""
                above = []
                j = idx - 2
                while j >= 0 and lines[j].startswith("--") and not SECTION_RE.match(lines[j]):
                    above.insert(0, lines[j].lstrip("- ").strip())
                    j -= 1
                above_text = " ".join(above)
                owner, src = None, ""
                im = BRACKET_RE.search(trailing)
                if im and im.group(1).strip() in modules:
                    owner, src = im.group(1).strip(), "table comment"
                if not owner:
                    om = re.search(r"owned by (\w+)", trailing)
                    if om and om.group(1) in modules:
                        owner, src = om.group(1), "table comment"
                if not owner and name in named:
                    owner, src = named[name], "file comment"
                if not owner:
                    om = re.search(r"(?<![\w.])owned by (\w+)", above_text, re.I)
                    if om and om.group(1) in modules and not re.search(r"\b\w+ (?:is|are) owned by", above_text):
                        owner, src = om.group(1), "comment above"
                if not owner and name in sec_owns:
                    owner, src = sec_owns[name], "section header"
                if not owner and sec_owner:
                    owner, src = sec_owner, "section header"
                if not owner and not sec_multi and file_default:
                    owner, src = file_default, "file header"
                if not owner and sec_multi:
                    t.candidates = sec_multi
                t.owner, t.owner_source = owner, src
                purpose = BRACKET_RE.sub("", trailing).strip(" -;")
                if not purpose and above:
                    purpose = above[-1]
                t.purpose = (purpose or sec_title)[:150]
                tables[name] = t
                current = t
                continue
            if current is not None:
                if line.startswith(")"):
                    current = None
                    continue
                code = line.split("--", 1)[0]
                colm = COLUMN_RE.match(code)
                if colm and colm.group(1) not in NOT_COLUMNS:
                    current.columns.append(colm.group(1))
                for cols, target in FK_TABLE_RE.findall(code):
                    fks.append((current.name, cols.replace(" ", ""), target, f"{rel(docs, path)}:{idx}"))
                im2 = FK_INLINE_RE.match(code)
                if im2 and im2.group(1).lower() not in NOT_COLUMNS and "FOREIGN KEY" not in code:
                    fks.append((current.name, im2.group(1), im2.group(2), f"{rel(docs, path)}:{idx}"))
                continue
            am = ALTER_FK_RE.match(line)
            if am:
                fks.append((am.group(1), am.group(2).replace(" ", ""), am.group(3), f"{rel(docs, path)}:{idx}"))
    return tables, fks, problems


def lab_stubs(docs):
    text = read(os.path.join(docs, STUBS))
    return sorted(set(re.findall(r"^CREATE TABLE (\w+)", text, re.M)))


# ----------------------------------------------------------------------------------------------- ADRs, verbs, events

def verb_forms(docs):
    text = read(os.path.join(docs, GLOSSARY))
    start = text.index("| Verb | Intent | Event form |")
    forms = {}
    for line in text[start:].splitlines()[2:]:
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip("|").split("|")]
        verb, form = cells[0], cells[-1]
        m = re.match(r"([A-Z][A-Za-z]+)", form)
        forms[verb] = m.group(1) if m and not form.startswith("none") else None
    return forms


def adr_files(docs):
    d = os.path.join(docs, "adr")
    return sorted(os.path.join(d, f) for f in os.listdir(d) if re.match(r"\d{4}-.*\.md$", f))


def parse_adrs(docs, modules, tables, forms):
    verbs = set(forms)
    event_forms = sorted({f for f in forms.values() if f}, key=len, reverse=True)
    adrs, events, commands, consumers = [], defaultdict(list), defaultdict(list), defaultdict(list)
    event_lines = defaultdict(list)
    for path in adr_files(docs):
        text = read(path)
        lines = text.splitlines()
        num = os.path.basename(path)[:4]
        title = re.sub(r"^# ADR-\d{4}:\s*", "", lines[0]).strip()
        status_line = next((l for l in lines[:6] if l.startswith("Status:")), "")
        sm = re.match(r"Status:\s*(\w+)(?:\s*\((\d{4}-\d{2}-\d{2})\))?", status_line)
        status = f"{sm.group(1)} {sm.group(2) or ''}".strip() if sm else "(no status line)"
        dm = re.search(r"Design items?: ([^.]+)\.", status_line)
        design = dm.group(1).strip() if dm else ""
        mod_count = defaultdict(int)
        for tok in re.findall(r"`([a-z_]+)`", text):
            if tok in modules:
                mod_count[tok] += 1
            elif tok in tables and tables[tok].owner:
                mod_count[tables[tok].owner] += 1
        ranked = sorted(mod_count.items(), key=lambda kv: (-kv[1], kv[0]))
        top = [m for m, c in ranked if c >= 3][:4]
        adrs.append({"num": num, "title": title, "status": status, "design": design, "modules": top,
                     "file": os.path.basename(path)})
        for lineno, line in enumerate(lines, start=1):
            loc = f"ADR-{num}:{lineno}"
            line_consumers = {a or b for a, b in CONSUMER_RE.findall(line)} - {"external", "transactional"}
            for c in line_consumers:
                consumers[c].append(loc)
            for tok in BACKTICK_PASCAL.findall(line):
                words = camel_words(tok)
                if words[0] in verbs:
                    if forms.get(words[0]) is not None or words[0] in ("Get", "List", "Evaluate"):
                        commands[tok].append(loc)
                    continue
                form = next((f for f in event_forms if tok.endswith(f) and len(tok) > len(f)), None)
                if form is None and words[-1].endswith("ed") and len(words) > 1:
                    form = words[-1]
                if form is None:
                    continue
                events[tok].append(loc)
                event_lines[tok].append((loc, line_consumers))
    return adrs, events, commands, consumers, event_lines


# ----------------------------------------------------------------------------------------------- rendering

def adr_links_from_generated(text):
    """Rewrite relative links copied from an ADR so they resolve from design/generated/."""
    def fix(m):
        target = m.group(1)
        if re.match(r"[a-z]+:", target):
            return m.group(0)
        path, _, anchor = target.partition("#")
        new = os.path.relpath(os.path.normpath(os.path.join("adr", path)), os.path.join("design", "generated"))
        return "](" + new.replace(os.sep, "/") + ("#" + anchor if anchor else "") + ")"
    return re.sub(r"\]\(([^)\s]+)\)", fix, text)


def md_escape(s):
    return s.replace("|", "\\|")


def owner_of(tables, name):
    t = tables.get(name)
    return t.owner if t else None


def render_data_map(docs, modules, tables, fks, stubs, findings):
    out = [HEADER, "# Data map (generated)\n",
           "Tables per owner module, from the DDL drafts in `docs/design/*.sql` and the owners their SQL comments state "
           "(ADR-0022 rule 7). Purpose is the table's own comment, else the comment above it, else its section title. "
           "Part of [architecture-overview.md](../architecture-overview.md), Part C.\n"]
    by_mod = defaultdict(list)
    for t in tables.values():
        by_mod[t.owner or "(no owner stated)"].append(t)
    out.append("## Count per module\n\n| Module | Layer | Tables |\n| --- | --- | --- |")
    for mod in sorted(by_mod, key=lambda m: (modules.get(m, (9,))[0], m)):
        layer = modules.get(mod, ("—",))[0]
        out.append(f"| `{mod}` | {layer} | {len(by_mod[mod])} |")
    out.append(f"| **total** | | **{len(tables)}** |\n")
    fk_out = defaultdict(list)
    for src, cols, tgt, loc in fks:
        fk_out[src].append((cols, tgt))
    for mod in sorted(by_mod, key=lambda m: (modules.get(m, (9,))[0], m)):
        out.append(f"## `{mod}`\n\n| Table | Purpose | Key references | Source |\n| --- | --- | --- | --- |")
        for t in sorted(by_mod[mod], key=lambda x: x.name):
            refs = sorted({tgt for cols, tgt in fk_out.get(t.name, []) if tgt != "company"})
            refs_s = ", ".join(f"`{r}`" for r in refs[:8]) + (" …" if len(refs) > 8 else "")
            out.append(f"| `{t.name}` | {md_escape(t.purpose)} | {refs_s} | {t.path}:{t.line} |")
        out.append("")
    out.append("## Cross-module foreign keys (report)\n")
    out.append("Foreign keys whose source and target tables have different stated owners. Foreign keys are not imports, "
               "and by design they may point up the layers (ADR-0022 rule 7: one schema, keys cross modules), so this "
               "is a report, not a check. No allowlist verdict is given here; edges to `company` are left out.\n")
    out.append("| From (module, layer) | Column(s) | To (module, layer) | Direction | Source |\n| --- | --- | --- | --- | --- |")
    rows = set()
    for src, cols, tgt, loc in fks:
        so, to = owner_of(tables, src), owner_of(tables, tgt)
        if tgt == "company" or not so or not to or so == to:
            continue
        sl, tl = modules.get(so, (0,))[0], modules.get(to, (0,))[0]
        direction = "down" if tl < sl else ("up" if tl > sl else "same layer")
        rows.add((so, src, cols, to, tgt, direction, loc, sl, tl))
    for so, src, cols, to, tgt, direction, loc, sl, tl in sorted(rows):
        out.append(f"| `{src}` ({so}, {sl}) | `{cols}` | `{tgt}` ({to}, {tl}) | {direction} | {loc} |")
    out.append(f"\n{len(rows)} cross-module foreign keys.\n")
    out.append("## Foreign keys to tables without a stated owner or without DDL\n")
    out.append("| From | Column(s) | To | Target state | Source |\n| --- | --- | --- | --- | --- |")
    rows2 = set()
    for src, cols, tgt, loc in fks:
        if tgt in tables and tables[tgt].owner:
            continue
        state = "lab stub" if tgt in stubs and tgt not in tables else ("no owner stated" if tgt in tables else "no DDL")
        rows2.add((src, cols, tgt, state, loc))
    for r in sorted(rows2):
        out.append(f"| `{r[0]}` | `{r[1]}` | `{r[2]}` | {r[3]} | {r[4]} |")
    out.append("\n## Polymorphic references\n")
    out.append("Column pairs `<x>_table` + `<x>_id` that point at any table. An FK scan cannot see them; invariants "
               "check them (e.g. INV-83 for `attachment_link`, ADR-0027 rule 2).\n")
    out.append("| Table | Owner | Columns | Source |\n| --- | --- | --- | --- |")
    for t in sorted(tables.values(), key=lambda x: x.name):
        for c in t.columns:
            if c.endswith("_table") and c[:-6] + "_id" in t.columns:
                out.append(f"| `{t.name}` | {t.owner or '—'} | `{c}`, `{c[:-6]}_id` | {t.path}:{t.line} |")
    out.append("\n## Findings: tables without an owner, and lab stubs\n")
    out.append("Listed for the review; no owner is invented. Each needs an owner stated in its DDL, or DDL of its own.\n")
    out.append("| Table | Finding | Where |\n| --- | --- | --- |")
    for name in sorted(findings):
        where = f"{tables[name].path}:{tables[name].line}" if name in tables else "docs/reviews/2026-11-14-design-validation/lab/00_stubs.sql"
        cand = f" Section owners: {', '.join(tables[name].candidates)}." if name in tables and tables[name].candidates else ""
        out.append(f"| `{name}` | {ACKNOWLEDGED[name]}.{cand} | {where} |")
    return "\n".join(out) + "\n"


def consumer_label(name, modules):
    return f"a consumer in `{name}`" if name in modules else f"`{name}`"


def render_events(tables, events, consumers, event_lines, modules, stubs):
    out = [HEADER, "# Event producer and consumer matrix (generated)\n",
           "Event types named in backticks in the ADRs, recognised by the event forms of the glossary's verb list "
           "(ADR-0004 rule 22), or by a final word in -ed. The producer module is the stated owner of the table the "
           "event's noun names (the noun of `<Noun><event form>`); `—` means no DDL table has that name. Consumers "
           "are the consumer names (`consumer \\`x\\``, `\\`x\\` consumer`) written on the same ADR line as the event. "
           "This is text extraction, not the registry: the registry's declarations (ADR-0013 rule 6; ADR-0058 rule 4 "
           "note in ADR-0008 rule 1) replace it at build step 0.\n",
           "| Event | Noun table | Producer module | Consumers named with it | First mentions |",
           "| --- | --- | --- | --- | --- |"]
    forms_cache = {}
    for ev in sorted(events):
        words = camel_words(ev)
        noun_table = None
        for k in range(len(words) - 1, 0, -1):
            cand = snake("".join(words[:k]))
            if cand in tables or cand in stubs:
                noun_table = cand
                break
        if noun_table in tables and tables[noun_table].owner:
            producer = tables[noun_table].owner
        elif noun_table in stubs:
            producer = "— (lab stub)"
        elif noun_table:
            producer = "— (no owner stated)"
        else:
            producer = "—"
        cons = sorted({c for loc, cs in event_lines[ev] for c in cs})
        locs = sorted(set(events[ev]), key=lambda s: (s.split(":")[0], int(s.split(":")[1])))
        shown = ", ".join(locs[:3]) + (f" (+{len(locs) - 3})" if len(locs) > 3 else "")
        out.append(f"| `{ev}` | {'`' + noun_table + '`' if noun_table else '—'} | {producer} | "
                   f"{', '.join(consumer_label(c, modules) for c in cons) or '—'} | {shown} |")
        forms_cache[ev] = producer
    out.append(f"\n{len(events)} event types.\n")
    out.append("## Consumers named in the ADRs\n\nA module name here means the ADR speaks of a consumer of that module "
               "without naming it.\n\n| Consumer | Mentions | First mentions |\n| --- | --- | --- |")
    for c in sorted(consumers):
        locs = sorted(set(consumers[c]), key=lambda s: (s.split(":")[0], int(s.split(":")[1])))
        out.append(f"| {consumer_label(c, modules)} | {len(locs)} | {', '.join(locs[:3])} |")
    return "\n".join(out) + "\n"


def render_adr_index(modules, adrs):
    out = [HEADER, "# ADR index by module and layer (generated)\n",
           "Title, status and design item come from each ADR's first lines. Modules are those named most often in the "
           "ADR (module names in backticks, plus tables in backticks counted for their stated owner; at least 3 "
           "mentions, at most 4 modules). This is a reading aid, not ownership.\n",
           "## By ADR\n", "| ADR | Title | Status | Design item | Modules | Layers |", "| --- | --- | --- | --- | --- | --- |"]
    for a in adrs:
        layers = sorted({modules[m][0] for m in a["modules"] if m in modules})
        out.append(f"| [ADR-{a['num']}](../../adr/{a['file']}) | {md_escape(a['title'])} | {a['status']} | "
                   f"{md_escape(a['design'])} | {', '.join('`' + m + '`' for m in a['modules'])} | "
                   f"{', '.join(map(str, layers))} |")
    out.append("\n## By module\n\n| Layer | Module | ADRs |\n| --- | --- | --- |")
    for mod, (layer, _) in sorted(modules.items(), key=lambda kv: (-kv[1][0], kv[0])):
        lst = [a["num"] for a in adrs if mod in a["modules"]]
        out.append(f"| {layer} | `{mod}` | {', '.join('ADR-' + n for n in lst) or '—'} |")
    out.append("\n## By layer\n\n| Layer | ADRs |\n| --- | --- |")
    for layer in sorted({l for l, _ in modules.values()}, reverse=True):
        lst = sorted({a["num"] for a in adrs for m in a["modules"] if modules.get(m, (0,))[0] == layer})
        out.append(f"| {layer} | {', '.join('ADR-' + n for n in lst) or '—'} |")
    out.append("\nADRs that name no module often enough (platform-wide or process ADRs): " +
               ", ".join("ADR-" + a["num"] for a in adrs if not a["modules"]) + ".")
    return "\n".join(out) + "\n"


def load_csv(docs, name):
    with open(os.path.join(docs, "catalogs", name), encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def render_cards(docs, modules, tables, events, commands, adrs, event_tables):
    settings, kinds, areas = load_csv(docs, "settings.csv"), load_csv(docs, "work-item-kinds.csv"), load_csv(docs, "authorization-areas.csv")
    out = [HEADER, "# Module cards (generated)\n",
           "One card per module of ADR-0022 rule 2, with the module's note in that table. Tables are those "
           "whose DDL states this owner. Events are those whose noun names one of its tables (see "
           "[event-matrix.md](event-matrix.md)). Commands and queries are names in backticks in the ADRs whose noun "
           "names one of its tables: a reading aid until the registry exists. Settings, work item kinds and "
           "authorization areas come from their catalogs' `area` or `module` columns.\n"]
    for mod, (layer, note) in sorted(modules.items(), key=lambda kv: (-kv[1][0], kv[0])):
        owned = sorted(t.name for t in tables.values() if t.owner == mod)
        evs = sorted(e for e, p in event_tables.items() if p == mod)
        cmds = []
        for c in commands:
            words = camel_words(c)
            for k in range(len(words), 1, -1):
                cand = snake("".join(words[1:k]))
                if cand in tables:
                    if tables[cand].owner == mod:
                        cmds.append(c)
                    break
        cmds = sorted(set(cmds))
        sets = sorted(r["key"] for r in settings if r.get("area") == mod)
        wik = sorted(r["code"] for r in kinds if r.get("module") == mod)
        aa = sorted(r["code"] for r in areas if r.get("module") == mod)
        adr_list = [a["num"] for a in adrs if mod in a["modules"]]
        out.append(f"## `{mod}` (layer {layer})\n")
        out.append(f"- **Note in ADR-0022 rule 2:** {adr_links_from_generated(md_escape(note)) if note else '—'}")
        out.append(f"- **Owned tables ({len(owned)}):** " + (", ".join(f"`{t}`" for t in owned) or "none stated"))
        out.append(f"- **Events produced ({len(evs)}):** " + (", ".join(f"`{e}`" for e in evs) or "none found"))
        shown = cmds[:25]
        out.append(f"- **Commands and queries named in ADRs ({len(cmds)}):** " +
                   (", ".join(f"`{c}`" for c in shown) + (" …" if len(cmds) > 25 else "") if cmds else "none found"))
        out.append(f"- **Settings ({len(sets)}):** " + (", ".join(f"`{s}`" for s in sets[:12]) + (" …" if len(sets) > 12 else "") if sets else "none in settings.csv"))
        out.append(f"- **Work item kinds ({len(wik)}):** " + (", ".join(f"`{k}`" for k in wik) or "none"))
        out.append(f"- **Authorization areas ({len(aa)}):** " + (", ".join(f"`{k}`" for k in aa) or "none"))
        out.append(f"- **ADRs:** " + (", ".join(f"[ADR-{n}](../../adr/{next(a['file'] for a in adrs if a['num'] == n)})" for n in adr_list) or "see [adr-index.md](adr-index.md)"))
        out.append("")
    return "\n".join(out) + "\n"


def build(docs):
    modules = module_map(docs)
    tables, fks, problems = parse_ddl(docs, modules)
    stubs = [s for s in lab_stubs(docs) if s not in tables]
    errors = list(problems)
    unowned = sorted(t.name for t in tables.values() if not t.owner)
    findings = set(unowned) | set(stubs)
    for name in sorted(findings - set(ACKNOWLEDGED)):
        where = f"{tables[name].path}:{tables[name].line}" if name in tables else STUBS
        errors.append(f"table {name} has no owner module stated ({where}); state it in the DDL or acknowledge it as a finding")
    for name in sorted(set(ACKNOWLEDGED) - findings):
        errors.append(f"acknowledged table {name} is no longer unowned or a stub; remove it from ACKNOWLEDGED")
    for t in tables.values():
        if t.owner and t.owner not in modules:
            errors.append(f"table {t.name} names owner {t.owner}, which is not a module of ADR-0022 rule 2 ({t.path}:{t.line})")
    forms = verb_forms(docs)
    adrs, events, commands, consumers, event_lines = parse_adrs(docs, modules, tables, forms)
    event_tables = {}
    for ev in events:
        words = camel_words(ev)
        for k in range(len(words) - 1, 0, -1):
            cand = snake("".join(words[:k]))
            if cand in tables:
                event_tables[ev] = tables[cand].owner
                break
    files = {
        "data-map.md": render_data_map(docs, modules, tables, fks, stubs, findings & set(ACKNOWLEDGED)),
        "event-matrix.md": render_events(tables, events, consumers, event_lines, modules, set(stubs)),
        "adr-index.md": render_adr_index(modules, adrs),
        "module-cards.md": render_cards(docs, modules, tables, events, commands, adrs, event_tables),
    }
    summary = {
        "tables": len(tables), "modules": len(modules), "foreign_keys": len(fks), "events": len(events),
        "per_module": {m: sum(1 for t in tables.values() if t.owner == m) for m in sorted(modules)},
        "unowned": unowned, "stubs": stubs,
    }
    return files, errors, summary


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--docs", default=DEFAULT_DOCS)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--summary", action="store_true", help="print tables per module and the findings")
    args = ap.parse_args()
    docs = os.path.abspath(args.docs)
    files, errors, summary = build(docs)
    if errors:
        for e in errors:
            print("error:", e, file=sys.stderr)
        sys.exit(2)
    out_dir = os.path.join(docs, OUT_DIR)
    if args.check:
        stale = []
        for name, content in sorted(files.items()):
            path = os.path.join(out_dir, name)
            if not os.path.exists(path) or read(path) != content:
                stale.append(name)
        if stale:
            print("stale: " + ", ".join(stale) + " (run gen_overview.py)", file=sys.stderr)
            sys.exit(1)
        print(f"ok: {len(files)} files current; {summary['tables']} tables, {summary['events']} events")
    else:
        os.makedirs(out_dir, exist_ok=True)
        for name, content in sorted(files.items()):
            with open(os.path.join(out_dir, name), "w", encoding="utf-8") as fh:
                fh.write(content)
        print(f"wrote {len(files)} files to {rel(docs, out_dir)}")
    if args.summary:
        for m, n in summary["per_module"].items():
            print(f"  {m}: {n}")
        print("  unowned:", ", ".join(summary["unowned"]))
        print("  stubs:", ", ".join(summary["stubs"]))


if __name__ == "__main__":
    main()
