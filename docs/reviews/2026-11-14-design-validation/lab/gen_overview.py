def consumer_label(name, modules):
    return f"a consumer in `{name}`" if name in modules else f"`{name}`"


def render_events(tables, events, consumers, event_lines, modules, stubs):
    out = [HEADER, "# Event producer and consumer matrix (generated)\n",
           "Event types named in backticks in the ADRs, recognised by the event forms of the glossary's verb list "
           "(ADR-0004 rule 22), or by a final word in -ed. The producer module is the stated owner of the table the "
           "event's noun names (the noun of `<Noun><event form>`); `—` means no DDL table has that name. Consumers "
           "are the consumer names (`consumer \\`x\\``, `\\`x\\` consumer`) written on the same ADR line as the event. "
           "This is text extraction, not the registry: the registry's declarations (ADR-0013 rule 6; ADR-0058 rule 4 "
           "note in ADR-0008 rule 1) replace it at build step 0.\n",
           "| Event | Noun table | Producer module | Consumers named with it | First mentions |",
           "| --- | --- | --- | --- | --- |"]
    forms_cache = {}
    for ev in sorted(events):
        words = camel_words(ev)
        noun_table = None
        for k in range(len(words) - 1, 0, -1):
            cand = snake("".join(words[:k]))
            if cand in tables or cand in stubs:
                noun_table = cand
                break
        if noun_table in tables and tables[noun_table].owner:
            producer = tables[noun_table].owner
        elif noun_table in stubs:
            producer = "— (lab stub)"
        elif noun_table:
            producer = "— (no owner stated)"
        else:
            producer = "—"
        cons = sorted({c for loc, cs in event_lines[ev] for c in cs})
        locs = sorted(set(events[ev]), key=lambda s: (s.split(":")[0], int(s.split(":")[1])))
        shown = ", ".join(locs[:3]) + (f" (+{len(locs) - 3})" if len(locs) > 3 else "")
        out.append(f"| `{ev}` | {'`' + noun_table + '`' if noun_table else '—'} | {producer} | "
                   f"{', '.join(consumer_label(c, modules) for c in cons) or '—'} | {shown} |")
        forms_cache[ev] = producer
    out.append(f"\n{len(events)} event types.\n")
    out.append("## Consumers named in the ADRs\n\nA module name here means the ADR speaks of a consumer of that module "
               "without naming it.\n\n| Consumer | Mentions | First mentions |\n| --- | --- | --- |")
    for c in sorted(consumers):
        locs = sorted(set(consumers[c]), key=lambda s: (s.split(":")[0], int(s.split(":")[1])))
        out.append(f"| {consumer_label(c, modules)} | {len(locs)} | {', '.join(locs[:3])} |")
    return "\n".join(out) + "\n"


