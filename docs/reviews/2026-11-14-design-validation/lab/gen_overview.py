def selftest(docs):
    """Errors for self-tests whose mutation the guard does not catch."""
    import shutil
    import tempfile
    out = []
    for name, fname, old, new, expect in SELFTESTS:
        with tempfile.TemporaryDirectory() as tmp:
            shutil.copytree(os.path.join(docs, "design"), os.path.join(tmp, "design"), ignore=shutil.ignore_patterns("generated"))
            path = os.path.join(tmp, "design", fname)
            text = read(path)
            if text.count(old) != 1:
                out.append(f"self-test '{name}': anchor not found once in {fname}")
                continue
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text.replace(old, new))
            errs, _ = check_keys_and_recorded_at(tmp)
            if not any(expect in e for e in errs):
                out.append(f"self-test '{name}': the guard missed it (errors: {errs[:2]})")
    return out


