def module_adrs(docs):
    """Module -> ADRs that ADR-0022 rule 2 names for it: ADR links in its note in the layer table, and the ADR of
    the note paragraph that adds a module ('`module` (layer n')."""
    text = read(os.path.join(docs, ADR0022))
    out = defaultdict(set)
    for name, (layer, note) in module_map(docs).items():
        out[name].update(re.findall(r"ADR-(\d{4})", note))
    for line in text.splitlines():
        nm = re.search(r"Note \(\[ADR-(\d{4})\]", line)
        if nm:
            for name in re.findall(r"`(\w+)` \(layer \d", line):
                out[name].add(nm.group(1))
    return out


def module_map(docs):
    """Module -> (layer, note) from ADR-0022 rule 2: the layer table and its '`module` (layer n' notes."""
    text = read(os.path.join(docs, ADR0022))
    modules = {}
    for line in text.splitlines():
        m = re.match(r"^\s*\|\s*(\d)\s*·\s*([A-Za-z ]+?)\s*\|(.*)\|\s*$", line)
        if not m:
            continue
        layer, cells = int(m.group(1)), m.group(3)
        depth, flat, notes, current = 0, [], {}, None
        i = 0
        while i < len(cells):  # drop parenthesised text, keeping it as the note of the module before it
            ch = cells[i]
            if ch == "(":
                depth += 1
                start = i
                while i < len(cells) and depth:
                    i += 1
                    if i < len(cells) and cells[i] == "(":
                        depth += 1
                    elif i < len(cells) and cells[i] == ")":
                        depth -= 1
                inner = cells[start + 1:i].strip()
                if current and not any(t != current and re.fullmatch(r"[a-z_]+", t) and f"`{t}`," in cells
                                       for t in re.findall(r"`([^`]+)`", inner)):
                    notes.setdefault(current, inner)
                i += 1
                continue
            flat.append(ch)
            mm = re.match(r"`(\w+)`(:\s*([^(|]+))?", cells[i:])
            if mm:
                current = mm.group(1)
                if mm.group(3):
                    notes.setdefault(current, mm.group(3).strip().rstrip(";,"))
            i += 1
        for name in re.findall(r"`(\w+)`", "".join(flat)):
            modules.setdefault(name, (layer, notes.get(name, "")))
    for name, layer in re.findall(r"`(\w+)` \(layer (\d)", text):
        modules.setdefault(name, (int(layer), "added by a note to ADR-0022 rule 2"))
    return modules


